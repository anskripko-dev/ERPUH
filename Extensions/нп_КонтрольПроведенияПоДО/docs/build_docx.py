OUT_DIR = Path(__file__).resolve().parent
FONT = "Times New Roman"


def set_run_font(run, size=14, bold=False, italic=False):
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor(0, 0, 0)


def set_paragraph_format(p, first_line=True, center=False, space_after=6, space_before=0):
    pf = p.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(space_after)
    pf.space_before = Pt(space_before)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pf.first_line_indent = Cm(0)
    else:
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        pf.first_line_indent = Cm(1.25) if first_line else Cm(0)


def add_title(doc, text):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=False, center=True, space_after=12, space_before=0)
    run = p.add_run(text.upper())
    set_run_font(run, size=16, bold=True)


def add_meta(doc, lines):
    for line in lines:
        p = doc.add_paragraph()
        set_paragraph_format(p, first_line=False, center=False, space_after=3)
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        run = p.add_run(line)
        set_run_font(run, size=12)


def add_heading_num(doc, text, level=1):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=False, center=False, space_after=8, space_before=12)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    size = 14 if level == 1 else 14
    run = p.add_run(text)
    set_run_font(run, size=size, bold=True)


def add_body(doc, text):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=True)
    run = p.add_run(text)
    set_run_font(run, size=14)


def add_bullet(doc, text, numbered=False, index=None):
    p = doc.add_paragraph()
    set_paragraph_format(p, first_line=False, space_after=4)
    p.paragraph_format.left_indent = Cm(1.25)
    prefix = f"{index}. " if numbered else "– "
    run = p.add_run(prefix + text)
    set_run_font(run, size=14)


def set_cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcBorders = OxmlElement("w:tcBorders")
    for edge in ("top", "left", "bottom", "right"):
        element = OxmlElement(f"w:{edge}")
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), "8")
        element.set(qn("w:color"), "000000")
        tcBorders.append(element)
    tcPr.append(tcBorders)


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True

    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(h)
        set_run_font(run, size=12, bold=True)
        set_cell_border(cell)

    for r_idx, row in enumerate(rows):
        for c_idx, value in enumerate(row):
            cell = table.rows[r_idx + 1].cells[c_idx]
            cell.text = ""
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(str(value))
            set_run_font(run, size=11)
            set_cell_border(cell)

    doc.add_paragraph()


def configure_document(doc):
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    style = doc.styles["Normal"]
    style.font.name = FONT
    style.font.size = Pt(14)
    style._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)


