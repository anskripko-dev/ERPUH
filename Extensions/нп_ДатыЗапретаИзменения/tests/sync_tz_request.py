def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
        return
    paragraph.add_run(text)


def set_cell_text(cell, text: str) -> None:
    if not cell.paragraphs:
        cell.text = text
        return
    set_paragraph_text(cell.paragraphs[0], text)
    for extra in cell.paragraphs[1:]:
        set_paragraph_text(extra, "")


def add_row(table: Table, values: list[str]) -> None:
    row = table.add_row()
    for cell, value in zip(row.cells, values, strict=True):
        set_cell_text(cell, value)


def rewrite_table(table: Table, rows: list[list[str]]) -> None:
    while len(table.rows) < len(rows):
        table.add_row()
    for r_idx, values in enumerate(rows):
        for c_idx, value in enumerate(values):
            set_cell_text(table.rows[r_idx].cells[c_idx], value)


def iter_body_blocks(doc: Document):
    parent = doc.element.body
    for child in parent.iterchildren():
        if child.tag == qn("w:p"):
            yield Paragraph(child, doc)
        elif child.tag == qn("w:tbl"):
            yield Table(child, doc)


def extract_tz(doc: Document) -> str:
    lines = [
        "Источник: ERP.2026.14 Заявка на доработку 1С ERP УХ (ред. 2)_1.docx",
        "Редакция 2 от 20.08.2026, актуализировано 06.09.2026 по решениям реализации",
        "",
    ]
    table_no = 0
    for block in iter_body_blocks(doc):
        if isinstance(block, Paragraph):
            text = block.text.strip()
            if text:
                lines.append(text)
                lines.append("")
            continue
        table_no += 1
        lines.append(f"--- ТАБЛИЦА {table_no} ---")
        for row in block.rows:
            lines.append(" | ".join(cell.text.replace("\n", " ").strip() for cell in row.cells))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


