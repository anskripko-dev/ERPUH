def _set_run_font(run, size_pt: int, bold: bool = False) -> None:
    run.bold = bold
    run.font.name = "Times New Roman"
    run.font.size = Pt(size_pt)
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(qn("w:ascii"), "Times New Roman")
    rfonts.set(qn("w:hAnsi"), "Times New Roman")
    rfonts.set(qn("w:eastAsia"), "Times New Roman")
    rfonts.set(qn("w:cs"), "Times New Roman")


def add_text(doc: Document, text: str, *, heading: bool = False, size: int = 12) -> Paragraph:
    paragraph = doc.add_paragraph()
    run = paragraph.add_run(text)
    _set_run_font(run, size, bold=heading)
    if heading:
        paragraph.paragraph_format.space_before = Pt(10)
        paragraph.paragraph_format.space_after = Pt(6)
    return paragraph


def add_table(doc: Document, rows: list[list[str]]) -> Table:
    table = doc.add_table(rows=len(rows), cols=len(rows[0]))
    table.style = "Table Grid"
    for r_idx, values in enumerate(rows):
        for c_idx, value in enumerate(values):
            cell = table.rows[r_idx].cells[c_idx]
            cell.text = ""
            paragraph = cell.paragraphs[0]
            run = paragraph.add_run(value)
            _set_run_font(run, 11, bold=r_idx == 0)
    return table


