def extract_appendix(doc: Document) -> str:
    lines = [
        "Источник: ERP.2026.14 Приложение 1 — порядок поиска даты запрета.docx",
        "К заявке ERP.2026.14, актуализировано 06.09.2026 по решениям реализации",
        "",
    ]
    table_no = 0
    for block in iter_body_blocks(doc):
        if isinstance(block, Paragraph):
            text = block.text.strip()
            if text:
                lines.append(text)
                lines.append("")
            continue
        table_no += 1
        lines.append(f"--- ТАБЛИЦА {table_no} ---")
        for row in block.rows:
            lines.append(" | ".join(cell.text.replace("\n", " ").strip() for cell in row.cells))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


